conflicted.setOwner('A'); await conflicted.load(); assert.equal(await conflicted.save(write), false);
assert.equal(conflicted.getState().context?.revision, 1);
assert.ok(conflicted.getState().error?.includes('latest version'));
let evaluationCalls: Array<{ requestId: string }> = [];
