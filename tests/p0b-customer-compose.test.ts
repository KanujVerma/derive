evaluating.setOwner('A'); await evaluating.load(); await evaluating.assess(null); assert.equal(evaluationCalls.length, 0);
const truth = { schemaVersion: 1 as const, snapshotId: 'snapshot', resolutionCaseId: 'case', caseRevision: 1, resolverVersion: 'v1', catalogReferences: { productId: null, variantId: null, formulaVersionId: null } } as any;
await evaluating.assess(truth); await evaluating.assess(truth);
assert.equal(evaluationCalls[0].requestId, evaluationCalls[1].requestId);
await evaluating.load(); await evaluating.assess(truth);
assert.notEqual(evaluationCalls[1].requestId, evaluationCalls[2].requestId);
