const saveOwner = new CustomerController({ ...gateway, load: async () => snapshot('A'), write: () => new Promise(resolve => { completeWrite = resolve; }) }, () => 'request');
saveOwner.setOwner('A'); await saveOwner.load(); const pendingSave = saveOwner.save(write); saveOwner.setOwner('B'); completeWrite?.({ replayed: false, revision: { ownerId: 'A' } }); assert.equal(await pendingSave, false); assert.equal(saveOwner.getState().context, null);
console.log('P0-B stale conflict and assessment retry semantics passed');
