import assert from 'node:assert/strict';
import { CustomerController } from '../src/presentation/personal-decision/customerController.ts';
import type { PersonalContextSnapshot, PersonalContextRequest } from '../src/contracts/PersonalContext.ts';
const snapshot = (ownerId: string, revision = 0): PersonalContextSnapshot => ({ version: 'personal-context-v1', ownerId, revision, profile: null, routine: null, experiences: [], historyRevision: null, historyTruncated: false, legacy: { source: 'legacy_free_context', profile: null, products: [], experiences: [], truncated: false } });
let finishLoad: ((v: PersonalContextSnapshot) => void) | undefined;
const requests: PersonalContextRequest[] = [];
let fail = true;
let loads = 0;
const gateway = { load: async () => { loads++; return snapshot('A', loads - 1); }, write: async (_owner: string, request: any) => { requests.push(request); if (fail) throw new Error('network'); return { replayed: false, revision: { ownerId: 'A' } } as any; }, evaluate: async () => ({ kind: 'unavailable' as const, reason: 'runtime_unavailable' }) };
let counter = 0;
const controller = new CustomerController(gateway, () => `request-${++counter}`);
controller.setOwner('A'); await controller.load();
assert.equal(controller.getState().context?.ownerId, 'A');
const write = { operation: 'save_routine' as const, routine: { completeness: 'partial' as const, items: [] } };
assert.equal(await controller.save(write), false);
fail = false;
assert.equal(await controller.save(write), true);
assert.equal((requests[0] as any).requestId, (requests[1] as any).requestId);
assert.equal(controller.getState().context?.revision, 1);
controller.setOwner('B');
assert.equal(controller.getState().context, null);
assert.equal(controller.getState().decision.kind, 'idle');
const delayed = new CustomerController({ ...gateway, load: () => new Promise(resolve => { finishLoad = resolve; }) }, () => 'id');
delayed.setOwner('A'); const pending = delayed.load(); delayed.setOwner('B'); finishLoad?.(snapshot('A')); await pending;
assert.equal(delayed.getState().context, null);
console.log('P0-B customer controller owner and retry semantics passed');
